import type { CoreInstallation, RuntimeStatus } from '../../src/shared/types';
import { dismissCoreInstallPrompt, expect, test } from './fixtures';

test('missing core prompts once per tab and retains runtime/settings installation entries without downloading', async ({ page, fixtures }) => {
  const before = await fixtures.bootstrap();
  expect(before.coreInstallation).toMatchObject({ state: 'idle', version: '1.19.32', installed: false });
  expect(before.coreInstallation.path).not.toBe('');
  const installRequests: string[] = [];
  page.on('request', request => { if (new URL(request.url()).pathname === '/api/core/install') installRequests.push(request.method()); });
  await page.goto('/');
  const dialog = page.getByRole('dialog', { name: '安装 Mihomo 内核', exact: true });
  await expect(dialog).toBeVisible();
  await expect(dialog).toContainText(before.coreInstallation.path);
  await expect(dialog).toContainText('1.19.32');
  await expect(dialog).toContainText('不需要独立安装器');
  await dismissCoreInstallPrompt(page);
  await expect(page.getByRole('button', { name: '管理内核安装', exact: true })).toBeEnabled();
  await expect(page.getByRole('button', { name: '重新应用', exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: '运行与设置', exact: true }).click();
  const panel = page.getByRole('region', { name: 'Mihomo 内核安装', exact: true });
  await expect(panel).toBeVisible();
  await expect(panel.getByRole('button', { name: '安装详情', exact: true })).toBeEnabled();
  await expect(page.getByRole('button', { name: '重新应用配置', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '检测与端口', exact: true }).click();
  await expect(panel).toBeVisible();
  await expect(panel.getByRole('button', { name: '重新检测内核', exact: true })).toBeEnabled();
  await page.reload();
  await expect(page.getByRole('heading', { name: '运行与设置', level: 1, exact: true })).toBeVisible();
  await expect(dialog).toHaveCount(0);
  await page.getByRole('button', { name: '管理内核安装', exact: true }).focus();
  await page.keyboard.press('Enter');
  await expect(dialog).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('button', { name: '管理内核安装', exact: true })).toBeFocused();
  const after = await fixtures.bootstrap();
  expect(after.revision).toBe(before.revision);
  expect(after.runtime.running).toBe(false);
  expect(installRequests).toEqual([]);
});

test('explicit missing-core inspection uses real API, keeps revision unchanged and never starts proxy', async ({ page, request, fixtures }) => {
  const before = await fixtures.bootstrap();
  const status = await request.get('/api/core/installation');
  expect(status.status()).toBe(200);
  expect(await status.json()).toMatchObject({ installed: false, state: 'idle', path: before.coreInstallation.path });
  await page.goto('/#/settings');
  await dismissCoreInstallPrompt(page);
  const panel = page.getByRole('region', { name: 'Mihomo 内核安装', exact: true });
  const inspected = page.waitForResponse(response => new URL(response.url()).pathname === '/api/core/inspect');
  await panel.getByRole('button', { name: '重新检测内核', exact: true }).click();
  const response = await inspected;
  expect(response.request().method()).toBe('POST');
  expect(response.request().postDataJSON()).toEqual({});
  expect(response.status()).toBe(200);
  const result = await response.json() as { coreInstallation: CoreInstallation; runtime: RuntimeStatus };
  expect(result.coreInstallation.installed).toBe(false);
  expect(result.coreInstallation.path).toBe(before.coreInstallation.path);
  expect(result.runtime).toMatchObject({ available: false, running: false });
  await expect(panel.getByRole('button', { name: '重新检测内核', exact: true })).toBeEnabled();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const after = await fixtures.bootstrap();
  expect(after.revision).toBe(before.revision);
  expect(after.runtime).toMatchObject({ available: false, running: false });
});
